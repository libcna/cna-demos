// XACT: an AudioEngine, a WaveBank and a SoundBank -- and a cue played by name.
#include <chrono>
#include <memory>
#include <thread>

#include "CnaDemos/Demo.hpp"
#include "Microsoft/Xna/Framework/Audio/AudioEngine.hpp"
#include "Microsoft/Xna/Framework/Audio/Cue.hpp"
#include "Microsoft/Xna/Framework/Audio/SoundBank.hpp"
#include "Microsoft/Xna/Framework/Audio/WaveBank.hpp"
#include "Microsoft/Xna/Framework/TitleLocation.hpp"
#include "System/ArgumentNullException.hpp"
#include "System/InvalidOperationException.hpp"

using namespace Microsoft::Xna::Framework::Audio;
using Microsoft::Xna::Framework::TitleLocation;

namespace
{
    // XACT does its work in AudioEngine::Update -- a game calls it every frame.
    void Pump(AudioEngine& engine, int milliseconds)
    {
        for (int t = 0; t < milliseconds; t += 10)
        {
            engine.Update();
            std::this_thread::sleep_for(std::chrono::milliseconds(10));
        }
    }

    void PlayCue(CnaDemos::DemoContext& ctx)
    {
        // The three files an XACT project builds (here generated by tools/xact_files.py):
        // global settings (.xgs), the waves (.xwb) and the sounds and cues that use them (.xsb).
        // WaveBank resolves relative paths from cwd; name the demo asset explicitly.
        AudioEngine engine("assets/xact/demo.xgs");
        WaveBank waves(&engine, TitleLocation::Path() + "/assets/xact/tones.xwb");
        SoundBank sounds(&engine, "assets/xact/tones.xsb");
        ctx.Check(AudioEngine::ContentVersion == 46,
                  "ContentVersion identifies the XACT generation used by the loaded settings and banks");
        ctx.Check(waves.getIsPreparedProperty(), "an in-memory wave bank is prepared as soon as it loads");

        bool emptyGetRefused = false;
        bool unknownGetRefused = false;
        bool emptyPlayRefused = false;
        bool unknownPlayRefused = false;
        try
        {
            const std::unique_ptr<Cue> unexpected(sounds.GetCue(""));
            static_cast<void>(unexpected);
        }
        catch (const System::ArgumentNullException&) { emptyGetRefused = true; }
        try
        {
            const std::unique_ptr<Cue> unexpected(sounds.GetCue("MissingCue"));
            static_cast<void>(unexpected);
        }
        catch (const System::InvalidOperationException&) { unknownGetRefused = true; }
        try { sounds.PlayCue(""); }
        catch (const System::ArgumentNullException&) { emptyPlayRefused = true; }
        try { sounds.PlayCue("MissingCue"); }
        catch (const System::InvalidOperationException&) { unknownPlayRefused = true; }
        ctx.Check(emptyGetRefused, "GetCue rejects an empty cue name with ArgumentNullException");
        ctx.Check(unknownGetRefused, "GetCue rejects an unknown cue name with InvalidOperationException");
        ctx.Check(emptyPlayRefused, "PlayCue rejects an empty cue name with ArgumentNullException");
        ctx.Check(unknownPlayRefused, "PlayCue rejects an unknown cue name with InvalidOperationException");

        // Fire and forget: the sound designer decided what "LowTone" sounds like; the game only
        // names the cue.
        sounds.PlayCue("LowTone");
        engine.Update();
        ctx.Check(sounds.getIsInUseProperty(), "while a cue plays, the sound bank is in use");
        // Completion follows the audio worker, not a guaranteed 100 ms margin over asset length.
        // Continue pumping actual XACT state, with a finite limit so a stuck cue still fails.
        const auto waitStart = std::chrono::steady_clock::now();
        const auto deadline = waitStart + std::chrono::seconds(3);
        while (sounds.getIsInUseProperty() && std::chrono::steady_clock::now() < deadline)
        {
            engine.Update();
            std::this_thread::sleep_for(std::chrono::milliseconds(10));
        }
        ctx.Print("waited {:.3f} s for natural XACT completion (3 s limit)",
                  std::chrono::duration<double>(std::chrono::steady_clock::now() - waitStart).count());
        ctx.Check(!sounds.getIsInUseProperty(), "after the 0.6 s sound ends, the bank is idle again");

        sounds.PlayCue("Beep");
        Pump(engine, 300);
    }
}

