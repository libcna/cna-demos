def rows(character: str) -> list:
    """The glyph's HEIGHT rows of WIDTH characters each."""
    glyph = GLYPHS[character]
    assert len(glyph) <= HEIGHT and all(len(row) == WIDTH for row in glyph), character
    return glyph + ["." * WIDTH] * (HEIGHT - len(glyph))
